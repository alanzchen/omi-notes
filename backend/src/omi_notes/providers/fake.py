"""Deterministic fake STT and LLM for tests and local smoke runs (no network, no keys)."""

from __future__ import annotations

from . import LlmRequest, LlmResult, SttRequest

_WORDS = (
    "we should review the quarterly plan and send the updated budget to the team before friday "
    "so everyone can agree on the launch date"
).split()


class FakeStt:
    """One utterance per speech block, alternating two speakers, placeholder text."""

    name = "fake"
    model = "fake-stt"

    def transcribe(self, request: SttRequest) -> dict:
        utterances = []
        for i, (start, end) in enumerate(request.blocks):
            n = max(3, min(len(_WORDS), int((end - start) * 2.5)))
            text = " ".join(_WORDS[:n]).capitalize() + "."
            step = (end - start) / n
            words = [
                {"word": w, "punctuated_word": w, "start": start + k * step, "end": start + (k + 1) * step,
                 "confidence": 0.99, "speaker": i % 2}
                for k, w in enumerate(_WORDS[:n])
            ]  # fmt: skip
            utterances.append(
                {"start": start, "end": end, "confidence": 0.99, "channel": 0, "transcript": text,
                 "words": words, "speaker": i % 2, "id": f"fake-{i}"}
            )  # fmt: skip
        return {
            "metadata": {"model_info": {"name": "fake"}, "duration": request.duration},
            "results": {"channels": [{"alternatives": [{"transcript": " ".join(u["transcript"] for u in utterances)}]}],
                        "utterances": utterances},
        }  # fmt: skip


class FakeLlm:
    """Keeps everything and derives a title from the transcript size."""

    name = "fake"
    model = "fake-llm"

    def summarize(self, request: LlmRequest) -> LlmResult:
        n = len(request.segments)
        first = request.segments[0]["text"] if request.segments else ""
        data = {
            "keep": True,
            "discard_reason": None,
            "title": f"Fake Conversation With {n} Segments",
            "emoji": "🧪",
            "category": "work",
            "overview": f"Deterministic fake summary of {n} transcript segments.",
            "sections": [{"heading": "What Was Said", "bullets": [first] if first else []}],
            "action_items": [
                {"description": "Review the fake transcript", "owner": "unknown", "owner_name": None,
                 "due_date": None, "context": "Generated by the fake LLM provider."}
            ],  # fmt: skip
            "decisions": [],
            "open_questions": [],
            "events": [],
            "people": [],
            "memorable_facts": [],
            "speaker_names": [],
            "tags": ["fake"],
        }
        return LlmResult(data=data, model=self.model)
