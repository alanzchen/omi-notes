"""Shared contract fixtures (contracts/fixtures/): Python-built ones must stay stable, Swift-built
ones (written by the iOS package's tests) must parse, match their expected JSON, decode, and be
accepted by the HTTP API together with their seals and events."""

import hashlib
import json
from pathlib import Path

import pytest

from omi_notes.audio.timeline import CaptureTimeline
from omi_notes.device.ble_frames import BleFrameAssembler
from omi_notes.device.ring_records import parse_record
from omi_notes.envelope import parse_envelope
from omi_notes.settings import BACKEND_DIR

from .conftest import AUTH, put_chunk

FIXTURES = BACKEND_DIR.parent / "contracts" / "fixtures"
PY = FIXTURES / "python"
SWIFT_DIR = FIXTURES / "swift"
SWIFT = sorted(SWIFT_DIR.glob("*.omnc")) if SWIFT_DIR.exists() else []
needs_swift = pytest.mark.skipif(not SWIFT, reason="no contracts/fixtures/swift/*.omnc yet (generated by the iOS package)")


def decode(body: bytes):
    env = parse_envelope(body)
    result = CaptureTimeline(env.header.frame_samples).decode_chunk(env, final=True)
    return env, result


@pytest.mark.parametrize("entry", json.loads((PY / "manifest.json").read_text()), ids=lambda e: e["file"])
def test_python_fixtures_match_manifest(entry):
    body = (PY / entry["file"]).read_bytes()
    assert hashlib.sha256(body).hexdigest() == entry["sha256"]
    env, result = decode(body)
    t0 = env.header.capture_started_at.timestamp()
    assert env.header.record_count == entry["record_count"]
    assert [{"start_offset_s": round(p.start - t0, 3), "samples": len(p.pcm)} for p in result.pieces] == entry["decoded_pieces"]


@needs_swift
@pytest.mark.parametrize("path", SWIFT, ids=lambda p: Path(p).name)
def test_swift_fixtures_parse_and_decode(path):
    body = path.read_bytes()
    env, result = decode(body)
    if env.header.record_count:
        assert result.pieces, "audio records should decode to PCM"
        assert result.stats["decode_errors"] == 0
    expected_path = path.with_suffix(".expected.json")
    if not expected_path.exists():
        return
    expected = json.loads(expected_path.read_text())
    assert hashlib.sha256(body).hexdigest() == expected["sha256"]
    header = env.header.model_dump(mode="json")
    for key, value in expected["header"].items():
        if key != "capture_started_at" and key in header:
            assert header[key] == value, key
    if env.header.payload_format == "ble_notifications_v1":
        records = env.ble_records()
        assert [
            {"t_offset_us": r.t_offset_us, "flags": r.flags, "seq": r.data[0] | r.data[1] << 8,
             "fragment_index": r.data[2], "length": len(r.data),
             "payload_sha256": hashlib.sha256(r.data[3:]).hexdigest()}
            for r in records
        ] == [{k: n[k] for k in ("t_offset_us", "flags", "seq", "fragment_index", "length", "payload_sha256")}
              for n in expected["notifications"]]  # fmt: skip
        asm = BleFrameAssembler()
        events = [e for r in records for e in asm.feed(r.t_offset_us, r.flags, r.data)] + asm.flush()
        fragments = sum(1 for n in expected["notifications"] if n["fragment_index"] > 0)
        # every notification completes a frame except continuation fragments
        frames = [e for e in events if e.kind == "frame"]
        assert len(frames) == len(records) - fragments
    if env.header.payload_format == "ring_records_v1":
        parsed = [parse_record(r) for r in env.ring_records()]
        assert [{"sequence": env.header.ring.first_sequence + i, "unix_ts": r.timestamp,
                 "frame_lengths": [len(f) for f in r.frames]} for i, r in enumerate(parsed)] == [
            {k: e[k] for k in ("sequence", "unix_ts", "frame_lengths")} for e in expected["ring_records"]
        ]  # fmt: skip


@needs_swift
def test_swift_fixtures_are_accepted_by_the_api(client):
    for path in SWIFT:
        env = parse_envelope(path.read_bytes())
        r = put_chunk(client, env.header.capture_id, env.header.chunk_sequence, path.read_bytes())
        assert r.status_code == 201, (path.name, r.text)
        seal = path.with_suffix(".seal.json")
        if seal.exists():
            r = client.put(f"/v1/captures/{env.header.capture_id}/seal", content=seal.read_bytes(), headers=AUTH)
            assert r.status_code == 200, (seal.name, r.text)
            assert r.json()["sealed"] is True
    for event in sorted(SWIFT_DIR.glob("event_*.json")):
        r = client.put(f"/v1/events/{hashlib.md5(event.name.encode()).hexdigest()[:8]}-0000-4000-8000-000000000000",
                       content=event.read_bytes(), headers=AUTH)  # fmt: skip
        assert r.status_code == 201, (event.name, r.text)
